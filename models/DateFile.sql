WITH CTE AS(
select 
DATE(TO_TIMESTAMP(STARTED_AT)) AS DATE_STARTED_AT,
RIDEABLE_TYPE,
START_LAT,
START_LNG,
END_LAT,
END_LNG from {{ source('demo', 'PARLA_RAW') }}
WHERE LOWER(TRIM(STARTED_AT)) <> 'started_at'),
CTE2 AS(
    SELECT DATE_STARTED_AT, RIDEABLE_TYPE, COUNT(RIDEABLE_TYPE),
    ROUND(AVG(START_LAT),2) AS AVG_START_LAT,
    ROUND(AVG(START_LNG),2) AS AVG_START_LNG,
    ROUND(AVG(END_LAT),2) AS AVG_END_LAN,
    ROUND(AVG(END_LNG),2) AS AVG_END_LAT,
    ROW_NUMBER()OVER(PARTITION BY DATE_STARTED_AT ORDER BY COUNT(RIDEABLE_TYPE) DESC ) AS ROW_NUM
    FROM CTE
    GROUP BY DATE_STARTED_AT, RIDEABLE_TYPE
    QUALIFY ROW_NUMBER()OVER(PARTITION BY DATE_STARTED_AT ORDER BY COUNT(RIDEABLE_TYPE) DESC ) = 1
)
SELECT * FROM CTE2